#!/usr/bin/env python3
"""
shipped_source_hashes.py — the list of every bundled source file version ever shipped.

On startup the app copies the bundled sources (library/sources) into the user's library. A file that's
already there is replaced by the new bundled version only when it is byte-for-byte some version we
shipped before, i.e. the user hasn't edited it (VisualSourceRegistry.ensureDefaultSources). This script
writes that list: the SHA-256 of every version of every file under library/sources (and its older home,
src/main/resources/default_sources) in git history, plus the working copy.

Run it after changing a bundled source: ./scripts/shipped_source_hashes.py
VisualSourceManifestTest.everyBundledSourceFileIsInTheShippedHashList fails while a current bundled file is
missing from the list.

./scripts/shipped_source_hashes.py --check writes nothing: it exits 1 when the list is not what this script
would write (naming any current bundled file whose hash is missing), 0 when it is up to date.
"""
import hashlib
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "src/main/resources/shipped_source_hashes.txt"
DIRS = ["library/sources", "src/main/resources/default_sources"]


def git(*args: str) -> bytes:
    return subprocess.run(["git", *args], cwd=ROOT, check=True, capture_output=True).stdout


def rel(path: str) -> str:
    for d in DIRS:
        if path.startswith(d + "/"):
            return path[len(d) + 1:]
    return path


def check(expected: str, current: set[tuple[str, str]]) -> int:
    """--check: compare without writing. 1 if the stored list differs from the generated one."""
    stored = OUT.read_text() if OUT.exists() else ""
    if stored == expected:
        print(f"{OUT.name} is up to date")
        return 0
    have = {tuple(l.split(" ", 1)) for l in stored.splitlines() if l and not l.startswith("#")}
    missing = sorted(current - have)
    for p, h in missing:
        print(f"missing: library/sources/{p} {h}")
    want = {tuple(l.split(" ", 1)) for l in expected.splitlines() if l and not l.startswith("#")}
    print(f"{OUT.name} is stale: {len(want - have)} entries to add, {len(have - want)} to drop "
          f"({len(missing)} of them current bundled files). Run scripts/shipped_source_hashes.py to rewrite it.")
    return 1


def main() -> int:
    entries: set[tuple[str, str]] = set()
    for d in DIRS:
        log = git("log", "--format=%H", "--", d).decode().split()
        for commit in log:
            listing = git("ls-tree", "-r", commit, "--", d).decode().splitlines()
            for line in listing:
                meta, path = line.split("\t", 1)
                blob = meta.split()[2]
                data = git("cat-file", "blob", blob)
                entries.add((rel(path), hashlib.sha256(data).hexdigest()))
    current: set[tuple[str, str]] = set()
    for f in (ROOT / "library/sources").rglob("*"):
        if f.is_file():
            current.add((str(f.relative_to(ROOT / "library/sources")), hashlib.sha256(f.read_bytes()).hexdigest()))
    entries |= current
    lines = [f"{p} {h}" for p, h in sorted(entries)]
    text = ("# Every shipped version of each bundled source file: <path under library/sources> <sha256>.\n"
            "# Generated by scripts/shipped_source_hashes.py; do not edit.\n" + "\n".join(lines) + "\n")
    if "--check" in sys.argv[1:]:
        return check(text, current)
    OUT.write_text(text)
    print(f"Wrote {len(lines)} hashes to {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
