#!/usr/bin/env python3
"""
shipped_source_hashes.py — the list of every bundled source file version ever shipped.

On startup the app copies the bundled sources (library/sources) into the user's library. A file that's
already there is replaced by the new bundled version only when it is byte-for-byte some version we
shipped before, i.e. the user hasn't edited it (VisualSourceRegistry.ensureDefaultSources). This script
writes that list: the SHA-256 of every version of every file under library/sources (and its older home,
src/main/resources/default_sources) in git history, plus the working copy.

Run it after changing a bundled source: ./scripts/shipped_source_hashes.py
ShippedSourceHashesTest fails while a current bundled file is missing from the list.
"""
import hashlib
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "src/main/resources/shipped_source_hashes.txt"
DIRS = ["library/sources", "src/main/resources/default_sources"]


def git(*args: str) -> bytes:
    return subprocess.run(["git", *args], cwd=ROOT, check=True, capture_output=True).stdout


def rel(path: str) -> str:
    for d in DIRS:
        if path.startswith(d + "/"):
            return path[len(d) + 1:]
    return path


def main() -> int:
    entries: set[tuple[str, str]] = set()
    for d in DIRS:
        log = git("log", "--format=%H", "--", d).decode().split()
        for commit in log:
            listing = git("ls-tree", "-r", commit, "--", d).decode().splitlines()
            for line in listing:
                meta, path = line.split("\t", 1)
                blob = meta.split()[2]
                data = git("cat-file", "blob", blob)
                entries.add((rel(path), hashlib.sha256(data).hexdigest()))
    for f in (ROOT / "library/sources").rglob("*"):
        if f.is_file():
            entries.add((str(f.relative_to(ROOT / "library/sources")), hashlib.sha256(f.read_bytes()).hexdigest()))
    lines = [f"{p} {h}" for p, h in sorted(entries)]
    OUT.write_text("# Every shipped version of each bundled source file: <path under library/sources> <sha256>.\n"
                   "# Generated by scripts/shipped_source_hashes.py; do not edit.\n" + "\n".join(lines) + "\n")
    print(f"Wrote {len(lines)} hashes to {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
